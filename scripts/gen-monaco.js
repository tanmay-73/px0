#!/usr/bin/env node
/**
 * scripts/gen-monaco.js
 *
 * Writes web/src/gen/monaco.js: Monaco's own editor.main.js import list, minus
 * the TypeScript/JavaScript, HTML, CSS and JSON language services (their web
 * workers are ~9 MB and language servers cover the same ground) and the LSP
 * client. Every editor feature and every Monarch syntax highlighter stays.
 * Run by scripts/build-web.js; rerun after bumping monaco-editor.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const esm = path.join(rootDir, 'node_modules', 'monaco-editor', 'esm', 'vs');
const main = path.join(esm, 'editor', 'editor.main.js');
const out = path.join(rootDir, 'web', 'src', 'gen', 'monaco.js');

export function genMonaco() {
  if (!fs.existsSync(main)) {
    throw new Error('monaco-editor is not installed: run `npm install` (or `bun install`) first');
  }
  const rel = path.relative(path.dirname(out), esm).split(path.sep).join('/');
  const drop = /languages\/features\/(css|html|json|typescript)\/|monaco-lsp-client|export \{ index as lsp \}|export \{ \w+ as (css|html|json|typescript) \}/;
  const lines = fs.readFileSync(main, 'utf8').split('\n')
    .filter(l => l.trim() && !drop.test(l))
    .map(l => l.replace(/(['"])\.\.\//g, `$1${rel}/`).replace(/(['"])\.\//g, `$1${rel}/editor/`));
  const body = '// Generated by scripts/gen-monaco.js from monaco-editor/esm/vs/editor/editor.main.js. Do not edit.\n' + lines.join('\n') + '\n';
  fs.mkdirSync(path.dirname(out), { recursive: true });
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log('[gen-monaco] wrote', path.relative(rootDir, genMonaco()));
}
